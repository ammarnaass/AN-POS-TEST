/**
 * خوارزمية البحث والمطابقة الذكية لاختيار الإجابة الأكثر دقة ومطابقة
 */
export function findBestAssistantAnswer(rawQuery: string): AssistantAnswer {
  const normalizedQuery = normalizeArabicText(rawQuery);
  const queryTokens = normalizedQuery.split(/\s+/).filter(t => t.length > 1);

  if (!queryTokens.length) {
    return buildGeneralFallback(rawQuery, 0);
  }

  let bestMatch: KnowledgeTopic | null = null;
  let highestScore = 0;

  for (const topic of KNOWLEDGE_BASE) {
    let score = 0;

    // 1. تطابق العبارات الجاهزة (Intents) - وزن عالي جداً
    for (const intent of topic.intents) {
      const normIntent = normalizeArabicText(intent);
      if (normalizedQuery === normIntent) {
        score += 250;
      } else if (normIntent.includes(normalizedQuery) || normalizedQuery.includes(normIntent)) {
        score += 160;
      }
    }

    // 2. تطابق الكلمات المفتاحية (Keywords)
    for (const kw of topic.keywords) {
      const normKw = normalizeArabicText(kw);
      if (normalizedQuery === normKw) {
        score += 120;
      } else if (normalizedQuery.includes(normKw)) {
        score += 60;
      } else {
        const kwTokens = normKw.split(/\s+/);
        for (const token of queryTokens) {
          if (kwTokens.includes(token)) {
            score += 25;
          } else if (kwTokens.some(kt => kt.length > 3 && (kt.includes(token) || token.includes(kt)))) {
            score += 12;
          }
        }
      }
    }

    // 3. تطابق عنوان الموضوع (Title)
    const normTitle = normalizeArabicText(topic.title);
    if (normalizedQuery.includes(normTitle) || normTitle.includes(normalizedQuery)) {
      score += 50;
    }
    for (const token of queryTokens) {
      if (normTitle.includes(token)) {
        score += 15;
      }
    }

    // 4. تطابق اسم التصنيف (Category)
    const normCat = normalizeArabicText(topic.category);
    for (const token of queryTokens) {
      if (normCat.includes(token)) {
        score += 10;
      }
    }

    // تعزيز درجات الأسئلة المحددة
    // كشف أسئلة العبوات وفاتورة الجملة (مشكلة المستخدم الحالية)
    if (
      (normalizedQuery.includes('فاتوره') || normalizedQuery.includes('جمله') || normalizedQuery.includes('بيع') || normalizedQuery.includes('قطع')) &&
      (normalizedQuery.includes('عبوه') || normalizedQuery.includes('كرتونه') || normalizedQuery.includes('قطع') || normalizedQuery.includes('كوليزاج'))
    ) {
      if (topic.id === 'wholesale_invoices_packaging') {
        score += 80;
      }
    }

    // كشف أسئلة الطابعات الحرارية والورق دون الخلط مع فواتير الجملة
    if (
      (normalizedQuery.includes('طابعه') || normalizedQuery.includes('حراريه') || normalizedQuery.includes('امبريمونت') || normalizedQuery.includes('80mm') || normalizedQuery.includes('58mm') || normalizedQuery.includes('وصل') || normalizedQuery.includes('ايصال')) &&
      !normalizedQuery.includes('جمله') && !normalizedQuery.includes('كرتونه')
    ) {
      if (topic.id === 'thermal_printers_setup') {
        score += 80;
      }
    }

    // كشف اختصارات لوحة المفاتيح F1-F12
    if (
      normalizedQuery.includes('اختصار') || normalizedQuery.includes('كيبورد') || normalizedQuery.includes('لوحه') ||
      queryTokens.some(t => /^f\d+$/i.test(t))
    ) {
      if (topic.id === 'keyboard_shortcuts') {
        score += 100;
      }
    }

    // كشف منتج حر Diver
    if (normalizedQuery.includes('منتج حر') || normalizedQuery.includes('صنف حر') || normalizedQuery.includes('diver') || normalizedQuery.includes('سلعه طارئه')) {
      if (topic.id === 'free_product_diver') {
        score += 120;
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = topic;
    }
  }

  // عتبة الثقة: إذا كانت النتيجة جيدة يتم تقديم الإجابة التخصصية
  if (bestMatch && highestScore >= 35) {
    return {
      id: String(Date.now()),
      sender: 'assistant',
      text: bestMatch.text,
      timestamp: new Date().toLocaleTimeString('ar-DZ', { hour: '2-digit', minute: '2-digit' }),
      badge: bestMatch.badge,
      steps: bestMatch.steps,
      proTip: bestMatch.proTip,
      route: bestMatch.route,
      routeLabel: bestMatch.routeLabel,
      suggestedQuestions: bestMatch.suggestedQuestions,
      confidenceScore: highestScore,
    };
  }

  return buildGeneralFallback(rawQuery, highestScore);
}

