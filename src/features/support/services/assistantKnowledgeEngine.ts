/**
 * دالة تطبيع النصوص العربية والمصطلحات المحلية
 * Normalizes Arabic diacritics, letter variations, and POS colloquialisms
 */
export function normalizeArabicText(input: string): string {
  if (!input) return '';

  return input
    .toLowerCase()
    // إزالة التشكيل والتنوين
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // إزالة التطويل
    .replace(/ـ+/g, '')
    // توحيد الهمزات والألف
    .replace(/[أإآٱ]/g, 'ا')
    // توحيد التاء المربوطة
    .replace(/ة/g, 'ه')
    // توحيد الألف المقصورة والياء
    .replace(/ى/g, 'ي')
    // توحيد الهمزات المركبة
    .replace(/[ؤئ]/g, 'ء')
    // استبدال علامات الترقيم بمسافات
    .replace(/[؟?.,!/\\:;()[\]{}#~`"'\-_]/g, ' ')
    // تحويل المسافات المتعددة لمسافة واحدة
    .replace(/\s+/g, ' ')
    .trim();
}

